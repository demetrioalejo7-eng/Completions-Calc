function bilinearLookup(xs, ys, table, x, y) {
  const cx = Math.min(Math.max(x, xs[0]), xs[xs.length - 1])
  const cy = Math.min(Math.max(y, ys[0]), ys[ys.length - 1])
  let i = 0
  while (i < xs.length - 2 && xs[i + 1] < cx) i++
  let j = 0
  while (j < ys.length - 2 && ys[j + 1] < cy) j++
  const x0 = xs[i],
    x1 = xs[i + 1]
  const y0 = ys[j],
    y1 = ys[j + 1]
  const tx = x1 === x0 ? 0 : (cx - x0) / (x1 - x0)
  const ty = y1 === y0 ? 0 : (cy - y0) / (y1 - y0)
  const q11 = table[i][j]
  const q21 = table[i + 1][j]
  const q12 = table[i][j + 1]
  const q22 = table[i + 1][j + 1]
  const top = q11 + tx * (q21 - q11)
  const bottom = q12 + tx * (q22 - q12)
  return top + ty * (bottom - top)
}

export function n2VolumeMultiplier(psia, tempF) {
  return bilinearLookup(N2_PRESSURES, N2_TEMPS, N2_VOLUME_MULTIPLIER, psia, tempF)
}

