export function n2PressureRatio(depthFt) {
  const rows = N2_PRESSURE_RATIO
  const d = Math.min(Math.max(depthFt, rows[0][0]), rows[rows.length - 1][0])
  for (let i = 0; i < rows.length - 1; i++) {
    const [d0, pr0] = rows[i]
    const [d1, pr1] = rows[i + 1]
    if (d >= d0 && d <= d1) {
      const t = d1 === d0 ? 0 : (d - d0) / (d1 - d0)
      return pr0 + t * (pr1 - pr0)
    }
  }
  return rows[rows.length - 1][1]
}

